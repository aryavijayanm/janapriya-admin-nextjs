// The port: "put these bytes somewhere, give them back, delete them."
// Deliberately dumb. It knows nothing about staff, compression, or filenames.
//
// Compression and key naming are service concerns -- the service resizes the
// image and decides the key, then hands both to a store that just obeys.
// That is what makes swapping LocalFileStore for R2FileStore a one-line
// change touching no business logic.

export interface SaveFileInput {
    /** Storage path, e.g. "staff/42/V1StGXR8.jpg". This is what gets saved in the database. */
    key: string;
    body: Buffer;
    /**
     * Passed through for object stores, which persist it as metadata and
     * return it as the Content-Type on read. LocalFileStore ignores it --
     * the filesystem has nowhere to put it -- so the local route handler
     * infers the type from the key's extension instead.
     */
    contentType: string;
}

export interface FileStore {
    save(input: SaveFileInput): Promise<void>;

    /** Idempotent: deleting a key that does not exist is not an error. */
    delete(key: string): Promise<void>;

    /**
     * The URL a browser should use to load this file.
     *
     * Async because a real object store returns a short-lived signed URL and
     * may need a network call to mint it. The local implementation only
     * builds a path, but the signature has to accommodate the eventual R2
     * one, or every call site would need rewriting later.
     */
    getUrl(key: string): Promise<string>;
}

/**
 * Keys are generated by our own code and are opaque by design -- never a
 * person's name, which would change, collide, and leak personal data into
 * URLs, logs and referrer headers.
 *
 * Validated anyway before any key reaches a filesystem path: if a malformed
 * key ever got into the database through some future bug, it must not be
 * able to climb out of the upload directory via "..".
 */
export function assertValidKey(key: string): void {
    const wellFormed = /^[a-zA-Z0-9][a-zA-Z0-9._/-]*$/.test(key);
    if (!wellFormed || key.includes("..") || key.includes("//")) {
        throw new Error(`Invalid storage key: ${key}`);
    }
}
